const language = getLocales()[0]?.languageCode?.toLowerCase() === 'zh' ? 'zh' : 'en';
export function t(key: MessageKey): string {
  return language === 'zh' ? zh[key] : en[key];
}

export function tf(key: MessageKey, values: Record<string, string | number>): string {
  return t(key).replace(/\{(\w+)\}/g, (_, name: string) => String(values[name] ?? ''));
}
